    def __init__(self, circuit_graph: nx.Graph):
        """
        Initialize with the full circuit graph generated by the current agent.
        """
        self.G = circuit_graph

    # ============================================================
    # Common helper functions
    # ============================================================
    def _safe_lower(self, value: object) -> str:
        return str(value).strip().lower() if value is not None else ""

    def _parse_bool_param(self, value: object, default: bool) -> bool:
        if value is None:
            return default
        if isinstance(value, bool):
            return value

        text = self._safe_lower(value)
        if text in {"1", "true", "yes", "y", "on"}:
            return True
        if text in {"0", "false", "no", "n", "off"}:
            return False
        return default

    def _contains_relative_voltage_reference(self, text: str) -> bool:
        """
        Check whether a voltage constraint contains a relative reference, such as VDD+0.3V
        or V_NEG to V_POS-1.5V.

        These expressions depend on dynamic supply rails and should not be compared as absolute thresholds.
        Otherwise, +0.3V could be incorrectly interpreted as <=0.3V.
        """
        if not text:
            return False

        lowered = self._safe_lower(text)
        symbol_token = (
            r"(?:vddio[a-z0-9_]*|vdd[a-z0-9_]*|vcc[a-z0-9_]*|vss[a-z0-9_]*|"
            r"gnd[a-z0-9_]*|agnd[a-z0-9_]*|dgnd[a-z0-9_]*|vref[a-z0-9_]*|"
            r"vbat[a-z0-9_]*|avcc[a-z0-9_]*|vio[a-z0-9_]*|vpos[a-z0-9_]*|"
            r"vneg[a-z0-9_]*|v_plus[a-z0-9_]*|v_minus[a-z0-9_]*|"
            r"v_pos[a-z0-9_]*|v_neg[a-z0-9_]*)"
        )

        # Explicit relative-description keywords.
        if any(token in lowered for token in ["relative", "supply rails", "must not exceed supply rails"]):
            return True

        # Common supply or reference rail symbols.
        if re.search(rf"\b{symbol_token}\b", lowered):
            return True

        # Arithmetic expressions involving rail symbols, such as v_pos-1.5v or vdd + 0.3v.
        if re.search(rf"\b{symbol_token}\b\s*[-+]\s*[+-]?\d", lowered):
            return True
        if re.search(rf"[+-]?\d(?:\.\d+)?\s*[-+]\s*\b{symbol_token}\b", lowered):
            return True

        return False

    def _parse_absolute_voltage_constraint(self, raw: object) -> Tuple[Optional[float], Optional[float], bool]:
        """
        Parse absolute voltage constraints only.

        Returns:
        - (vmin, vmax, True): successfully parsed as an absolute range or threshold.
        - (None, None, False): not parseable or detected as a relative constraint and should be skipped.
        """
        text = self._safe_lower(raw)
        if not text:
            return None, None, True

        if self._contains_relative_voltage_reference(text):
            return None, None, False

        range_match = re.search(r"([+-]?\d+(?:\.\d+)?)\s*v?\s*(?:-|~|to)\s*([+-]?\d+(?:\.\d+)?)\s*v?", text)
        if range_match:
            lo = float(range_match.group(1))
            hi = float(range_match.group(2))
            return min(lo, hi), max(lo, hi), True

        op_match = re.search(r"(<=|<|>=|>|=)?\s*([+-]?\d+(?:\.\d+)?)\s*v", text)
        if not op_match:
            return None, None, False

        op = op_match.group(1) or "<="
        value = float(op_match.group(2))
        if op in {"<=", "<"}:
            return None, value, True
        if op in {">=", ">"}:
            return value, None, True
        return value, value, True

    def _component_pins(self, comp_id: str) -> List[str]:
        if not self.G.has_node(comp_id):
            return []
        return [n for n in self.G.neighbors(comp_id) if self.G.nodes[n].get("type") == "Pin"]

    def _pin_parent_component(self, pin_id: str) -> Optional[str]:
        if not self.G.has_node(pin_id):
            return None
        comps = [n for n in self.G.neighbors(pin_id) if self.G.nodes[n].get("type") == "Component"]
        return comps[0] if comps else None

    def _pin_connected_nets(self, pin_id: str) -> List[str]:
        if not self.G.has_node(pin_id):
            return []
        return [n for n in self.G.neighbors(pin_id) if self.G.nodes[n].get("type") == "Net"]

    def _net_connected_pins(self, net_id: str) -> List[str]:
        if not self.G.has_node(net_id):
            return []
        return [n for n in self.G.neighbors(net_id) if self.G.nodes[n].get("type") == "Pin"]

    def _resolve_pin_node(self, comp_id: str, pin_ref: object) -> Optional[str]:
        """
        Resolve the following input formats:
        1) Full node ID: U1_Pin3.
        2) Pin number: 3 / "3".
        3) Pin name: VCC / FB / OUT.
        4) Legacy form: U1_VCC.
        """
        if pin_ref is None:
            return None

        token = str(pin_ref).strip()
        if not token:
            return None

        # Allow RefDes.PinToken form, such as Y1.1. If RefDes matches, resolve only the right side.
        if "." in token:
            left, right = token.split(".", 1)
            if self._safe_lower(left) == self._safe_lower(comp_id):
                token = right.strip()
                if not token:
                    return None
        elif token.lower().startswith(f"{self._safe_lower(comp_id)}_"):
            # Also strip RefDes_ if present, such as U1_Pin5 -> Pin5.
            token = token[len(comp_id) + 1:].strip()
            if not token:
                return None

        if self.G.has_node(token) and self.G.nodes[token].get("type") == "Pin":
            return token

        direct = f"{comp_id}_{token}"
        if self.G.has_node(direct) and self.G.nodes[direct].get("type") == "Pin":
            return direct

        numbered = f"{comp_id}_Pin{token}"
        if self.G.has_node(numbered) and self.G.nodes[numbered].get("type") == "Pin":
            return numbered

        token_l = token.lower()

        # Support aliases such as pin_1 / pin-1 / pin1.
        m = re.fullmatch(r"pin[_\-\s]*([0-9]+)", token_l)
        if m:
            pin_num = m.group(1)
            alias_direct = f"{comp_id}_{pin_num}"
            alias_numbered = f"{comp_id}_Pin{pin_num}"
            if self.G.has_node(alias_direct) and self.G.nodes[alias_direct].get("type") == "Pin":
                return alias_direct
            if self.G.has_node(alias_numbered) and self.G.nodes[alias_numbered].get("type") == "Pin":
                return alias_numbered

        for pin_node in self._component_pins(comp_id):
            attrs = self.G.nodes[pin_node]
            name_l = self._safe_lower(attrs.get("name"))
            num_l = self._safe_lower(attrs.get("pin_number"))
            pin_id_l = pin_node.lower()
            if token_l in {name_l, num_l}:
                return pin_node
            if num_l and token_l in {f"pin{num_l}", f"pin_{num_l}", f"pin-{num_l}"}:
                return pin_node

            # Fix hidden issue 14: add boundary checks to prevent token "1" from matching "11".
            if re.search(rf"_{re.escape(token_l)}$", pin_id_l) or re.search(rf"pin{re.escape(token_l)}$", pin_id_l):
                return pin_node

            # Alias mapping fallback for "Pin5" => "VOUT".
            if m:
                pin_num = m.group(1)
                if pin_num == num_l:
                    return pin_node

            # Direct text inclusion match: "5" matches "Pin5" or "5".
            if token_l == f"pin{num_l}" or token_l == f"pin_{num_l}":
                return pin_node

        return None

    def _resolve_pin_list(self, comp_id: str, values: Iterable[object]) -> Tuple[List[str], List[str]]:
        resolved: List[str] = []
        missing: List[str] = []
        for v in values:
            pin = self._resolve_pin_node(comp_id, v)
            if pin:
                resolved.append(pin)
            else:
                missing.append(str(v))
        return resolved, missing

    def _collect_param_pins(self, params: Dict, *keys: str) -> List[object]:
        out: List[object] = []
        for k in keys:
            val = params.get(k)
            if val is None:
                continue
            if isinstance(val, list):
                out.extend(val)
            else:
                out.append(val)
        return out

    def _infer_component_kind(self, comp_id: str) -> str:
        attrs = self.G.nodes[comp_id]
        pt = self._safe_lower(attrs.get("part_type"))
        pn = self._safe_lower(attrs.get("part_number"))
        ref = self._safe_lower(comp_id)

        text = " ".join([pt, pn, ref])
        if not text.strip():
            return "unknown"

        # Fix hidden issue 13: when inferring from the first letter of RefDes, require a following digit
        # to avoid misclassifying names such as DAC or LED as D/L-based components.
        if "resistor" in text or re.match(r"^r\d+", ref):
            return "resistor"
        if "capacitor" in text or "cap" in text or re.match(r"^c\d+", ref):
            return "capacitor"
        if "inductor" in text or re.match(r"^l\d+", ref):
            return "inductor"
        if "ferrite" in text or "bead" in text:
            return "ferritebead"
        if "diode" in text or re.match(r"^d\d+", ref) or "schottky" in text or "tvs" in text or "esd" in text:
            return "diode"
        if "crystal" in text or "resonator" in text or "osc" in text:
            return "resonator"
        if any(k in text for k in ["nettie", "net_tie", "net-tie", "net tie"]):
            return "nettie"
        if any(k in text for k in ["testpoint", "test_point", "test-point"]):
            return "testpoint"
        if any(k in text for k in ["jumper", "wirelink", "wire_link", "solderbridge", "solder_bridge"]):
            return "jumper"
        if any(k in text for k in ["digipot", "digitalpot", "potentiometer", "trimpot"]):
            return "digipot"
        if any(k in text for k in ["resistorarray", "resistor_array", "resistor network", "resistor ladder"]):
            return "resistorladder"
        if bool(re.search(r"\bdac\b", text)) or ref.startswith("dac"):
            return "dac"

        return pt or pn or "unknown"

    def _normalize_kind_token(self, raw_kind: object) -> str:
        token = self._safe_lower(raw_kind)
        compact = token.replace("-", "").replace("_", "").replace(" ", "")

        aliases = {
            "ferrite": "ferritebead",
            "bead": "ferritebead",
            "ferritebead": "ferritebead",
            "nettie": "nettie",
            "nettiecomponent": "nettie",
            "testpoint": "testpoint",
            "tp": "testpoint",
            "jumper": "jumper",
            "wirelink": "jumper",
            "solderbridge": "jumper",
            "resistorladder": "resistorladder",
            "resistorarray": "resistorladder",
            "resistornetwork": "resistorladder",
            "digipot": "digipot",
            "digitalpot": "digipot",
            "potentiometer": "digipot",
            "trimpot": "digipot",
            "dacoutput": "dac_output",
            "dac": "dac",
        }
        return aliases.get(compact, compact)

    def _parse_kind_set_param(self, params: Dict, key: str, default_kinds: Set[str]) -> Set[str]:
        raw = params.get(key)
        if raw is None:
            values = list(default_kinds)
        elif isinstance(raw, list):
            values = [str(v) for v in raw]
        elif isinstance(raw, str):
            values = re.split(r"[,;|]", raw)
        else:
            values = list(default_kinds)

        out: Set[str] = set()
        for v in values:
            t = self._normalize_kind_token(v)
            if t:
                out.add(t)
        return out or {self._normalize_kind_token(v) for v in default_kinds if self._normalize_kind_token(v)}

    def _is_return_like_net(self, net_id: str) -> bool:
        if not self.G.has_node(net_id):
            return False
        if self._is_net_type(net_id, "ground"):
            return True

        name = self._safe_lower(self.G.nodes[net_id].get("name", net_id))
        return any(k in name for k in ["return", "rtn", "ret", "vss", "pgnd", "agnd", "dgnd", "sgnd"])

    def _net_matches_reference(self, net_id: str, reference: str) -> bool:
        ref = self._safe_lower(reference)
        if ref in {"ground", "gnd"}:
            return self._is_net_type(net_id, "ground")
        if ref in {"return", "load_return", "power_return"}:
            return self._is_return_like_net(net_id)
        if ref in {"power", "vout", "output", "powerout"}:
            return self._is_net_type(net_id, "power")
        return self._is_net_type(net_id, reference)

    def _has_path_with_required_bridge(
        self,
        seed_nets: Iterable[str],
        *,
        target_predicate: Callable[[str], bool],
        max_hops: int,
        allowed_bridge_kinds: Set[str],
        required_bridge_kinds: Set[str],
        exclude_components: Optional[Set[str]] = None,
        component_gate: Optional[Callable[[str], bool]] = None,
    ) -> bool:
        exclude_components = exclude_components or set()
        allowed = {self._normalize_kind_token(k) for k in allowed_bridge_kinds if self._normalize_kind_token(k)}
        required = {self._normalize_kind_token(k) for k in required_bridge_kinds if self._normalize_kind_token(k)}

        queue: deque[Tuple[str, int, bool]] = deque()
        visited: Set[Tuple[str, bool]] = set()

        for net in seed_nets:
            if not self.G.has_node(net) or self.G.nodes[net].get("type") != "Net":
                continue
            state = (net, False)
            if state not in visited:
                visited.add(state)
                queue.append((net, 0, False))

        while queue:
            current_net, depth, used_required = queue.popleft()
            if depth >= max_hops:
                continue

            for comp in self._components_on_net(current_net, exclude=exclude_components):
                comp_kind = self._normalize_kind_token(self._infer_component_kind(comp))
                if comp_kind not in allowed:
                    continue
                if component_gate is not None and not component_gate(comp):
                    continue

                next_used_required = used_required or (comp_kind in required)
                for next_net in self._component_nets(comp):
                    if next_net == current_net:
                        continue
                    if target_predicate(next_net) and (next_used_required or not required):
                        return True
                    state = (next_net, next_used_required)
                    if state in visited:
                        continue
                    visited.add(state)
                    queue.append((next_net, depth + 1, next_used_required))

        return False

    def _min_bridge_count_between_net_sets(
        self,
        seed_nets: Iterable[str],
        target_nets: Iterable[str],
        *,
        allowed_bridge_kinds: Set[str],
        max_hops: int,
        exclude_components: Optional[Set[str]] = None,
        component_gate: Optional[Callable[[str], bool]] = None,
    ) -> Optional[int]:
        exclude_components = exclude_components or set()
        allowed = {self._normalize_kind_token(k) for k in allowed_bridge_kinds if self._normalize_kind_token(k)}

        targets = {
            n
            for n in target_nets
            if self.G.has_node(n) and self.G.nodes[n].get("type") == "Net"
        }
        if not targets:
            return None

        queue: deque[Tuple[str, int]] = deque()
        visited_depth: Dict[str, int] = {}

        for net in seed_nets:
            if not self.G.has_node(net) or self.G.nodes[net].get("type") != "Net":
                continue
            if net in targets:
                return 0
            visited_depth[net] = 0
            queue.append((net, 0))

        while queue:
            current_net, depth = queue.popleft()
            if depth >= max_hops:
                continue

            for comp in self._components_on_net(current_net, exclude=exclude_components):
                kind = self._normalize_kind_token(self._infer_component_kind(comp))
                if kind not in allowed:
                    continue
                if component_gate is not None and not component_gate(comp):
                    continue

                next_depth = depth + 1
                for next_net in self._component_nets(comp):
                    if next_net == current_net:
                        continue
                    if next_net in targets:
                        return next_depth
                    best = visited_depth.get(next_net)
                    if best is not None and best <= next_depth:
                        continue
                    visited_depth[next_net] = next_depth
                    queue.append((next_net, next_depth))

        return None

    def _component_matches_kind(self, comp_id: str, kind: str) -> bool:
        if not self.G.has_node(comp_id):
            return False

        target = self._normalize_kind_token(kind)
        actual = self._normalize_kind_token(self._infer_component_kind(comp_id))

        if target in {"resistor", "inductor", "capacitor", "diode", "nettie", "testpoint", "jumper", "digipot", "resistorladder", "dac"}:
            return actual == target
        if target in {"ferritebead", "ferrite", "bead"}:
            return actual in {"ferritebead", "inductor"}
        if target in {"crystal", "resonator", "osc"}:
            return actual == "resonator"

        return target in actual

    def _net_voltage(self, net_id: str) -> Optional[float]:
        if not self.G.has_node(net_id):
            return None

        def _extract_voltage_token(raw_value: object) -> Optional[float]:
            if raw_value is None:
                return None

            if isinstance(raw_value, (int, float)):
                return float(raw_value)

            text = self._safe_lower(raw_value)
            if not text:
                return None

            compact = re.sub(r"\s+", "", text)
            # Try rail-style first: 3V3 / 1V8 / 5V0.
            rail = re.search(r"(?<![0-9a-z])([+-]?\d+)v(\d{1,3})(?!\d)", compact)
            if rail:
                try:
                    return float(f"{rail.group(1)}.{rail.group(2)}")
                except Exception:
                    pass

            # Then plain unit style: 3.3V / 5V.
            plain = re.search(r"(?<![0-9a-z])([+-]?\d+(?:\.\d+)?)v(?!\d)", compact)
            if plain:
                try:
                    return float(plain.group(1))
                except Exception:
                    return None

            return None

        raw = self.G.nodes[net_id].get("voltage")
        parsed_raw = _extract_voltage_token(raw)
        if parsed_raw is not None:
            return parsed_raw

        name = self._safe_lower(self.G.nodes[net_id].get("name", net_id))
        parsed_name = _extract_voltage_token(name)
        if parsed_name is not None:
            return parsed_name

        return None

    def _is_net_type(self, net_id: str, expected_type: str) -> bool:
        expected = self._safe_lower(expected_type)
        if not expected:
            return True

        attrs = self.G.nodes[net_id]
        explicit = self._safe_lower(attrs.get("net_type"))
        name = self._safe_lower(attrs.get("name", net_id))

        if explicit and (expected in explicit or explicit in expected):
            return True

        if expected in {"ground", "gnd", "agnd", "dgnd"}:
            if any(x in name for x in ["gnd", "ground", "agnd", "dgnd", "pgnd"]):
                return True
            for p in self._net_connected_pins(net_id):
                if self._safe_lower(self.G.nodes[p].get("electrical_type")) == "ground":
                    return True
            return False

        if expected in {"power", "powerin", "powerout", "vcc", "vdd", "vin", "vout"}:
            if any(x in name for x in ["vcc", "vdd", "vin", "vout", "3v", "5v", "12v", "power"]):
                return True
            for p in self._net_connected_pins(net_id):
                et = self._safe_lower(self.G.nodes[p].get("electrical_type"))
                if et in {"power", "powerin", "powerout"}:
                    return True
            return False

        return expected in name or expected in explicit

    def _is_net_type_strict(self, net_id: str, expected_type: str) -> bool:
        """
        Strict net-type check:
        - Only uses the Net node's own attributes, such as name/net_type.
        - Does not infer net type from connected pin electrical_type.

        Applicable use case:
        - Enforce explicit network-class rules while avoiding false positives caused by reverse inference
          from pin electrical_type to net type.
        """
        if not self.G.has_node(net_id):
            return False

        expected = self._safe_lower(expected_type)
        if not expected:
            return True

        attrs = self.G.nodes[net_id]
        explicit = self._safe_lower(attrs.get("net_type"))
        name = self._safe_lower(attrs.get("name", net_id))

        if explicit and (expected in explicit or explicit in expected):
            return True

        if expected in {"ground", "gnd", "agnd", "dgnd", "pgnd", "vss", "vssa"}:
            return any(x in name for x in ["gnd", "ground", "agnd", "dgnd", "pgnd", "vss", "vssa"])

        if expected in {"power", "powerin", "powerout", "vcc", "vdd", "vin", "vout"}:
            return any(x in name for x in ["vcc", "vdd", "vin", "vout", "3v", "5v", "12v", "power"])

        return expected in name or expected in explicit

    def _components_on_net(self, net_id: str, exclude: Optional[Set[str]] = None) -> Set[str]:
        exclude = exclude or set()
        comps: Set[str] = set()
        for pin in self._net_connected_pins(net_id):
            parent = self._pin_parent_component(pin)
            if parent and parent not in exclude:
                comps.add(parent)
        return comps

    def _component_nets(self, comp_id: str) -> Set[str]:
        nets: Set[str] = set()
        for p in self._component_pins(comp_id):
            for n in self._pin_connected_nets(p):
                nets.add(n)
        return nets

    def _ohm_suffix_factor(self, suffix: str) -> Optional[float]:
        """
        Return the multiplier for a resistance suffix.

        Notes:
        - Letter case is semantically meaningful: M = mega, m = milli.
        - mR/mr is treated as milliohm.
        """
        if suffix in {"", "R", "r"}:
            return 1.0
        if suffix in {"K", "k"}:
            return 1e3
        if suffix == "M":
            return 1e6
        if suffix in {"G", "g"}:
            return 1e9
        if suffix in {"m", "mR", "mr"}:
            return 1e-3
        return None

    def _parse_ohms(self, raw: object) -> Optional[float]:
        """
        Parse a resistance string and return the value in ohms.

        Supported examples:
        - 4.7K / 10k / 1M / 2m / 10mR.
        - 4R7 / 2K2 / 1M0, where the unit letter acts as the decimal point.
        - 0.22Ohm / 0.22Ω.
        - RES_49.9K_1% / RES_4K7, as part-number-style strings.

        Key point:
        - Preserve and parse the original suffix case before lowercasing, so M and m are not confused.
        """
        if raw is None:
            return None

        if isinstance(raw, (int, float)):
            return float(raw)

        text = str(raw).strip()
        if not text:
            return None

        compact = re.sub(r"\s+", "", text)
        compact = compact.replace("Ω", "ohm")
        compact = re.sub(r"(?i)ohms?$", "", compact)

        # Support common part-number naming forms: RES_49.9K_1%, RES_4K7, etc.
        if re.match(r"(?i)^res[_-]", compact):
            compact = re.sub(r"(?i)^res[_-]", "", compact, count=1)
            compact = re.split(r"[_-]", compact, maxsplit=1)[0]

        if not compact:
            return None

        # Handle common EDA notation: 4R7 / 2K2 / 1M0.
        embedded = re.fullmatch(r"([+-]?\d+)([RrKkMmGg])(\d+)", compact)
        if embedded:
            left, unit_ch, right = embedded.groups()
            factor = self._ohm_suffix_factor(unit_ch)
            if factor is None:
                return None
            try:
                return float(f"{left}.{right}") * factor
            except Exception:
                return None

        suffix = ""
        numeric_token = compact

        if len(compact) >= 2 and compact[-2:] in {"mR", "mr"}:
            suffix = compact[-2:]
            numeric_token = compact[:-2]
        elif compact[-1].isalpha():
            suffix = compact[-1]
            numeric_token = compact[:-1]

        factor = self._ohm_suffix_factor(suffix)
        if factor is None:
            return None

        numeric_token = numeric_token.strip()
        if not numeric_token:
            return None

        try:
            return float(numeric_token) * factor
        except Exception:
            return None

    def _parse_range_ohms(self, raw: object) -> Tuple[Optional[float], Optional[float]]:
        if raw is None:
            return None, None

        s = str(raw).strip()
        if not s or s.lower() == "any":
            return None, None

        # Use case-insensitive matching only for separators; preserve original case in numeric tokens.
        parts = re.split(r"-|~|to", s, flags=re.IGNORECASE)
        if len(parts) == 2:
            lo = self._parse_ohms(parts[0].strip())
            hi = self._parse_ohms(parts[1].strip())
            if lo is not None and hi is not None:
                return min(lo, hi), max(lo, hi)

        v = self._parse_ohms(s)
        if v is not None:
            return v, v
        return None, None

    def _resistors_on_net(self, net_id: str) -> List[str]:
        return [c for c in self._components_on_net(net_id) if self._component_matches_kind(c, "resistor")]

    def _component_resistance_ohms(self, comp_id: str) -> Optional[float]:
        if not self.G.has_node(comp_id):
            return None

        attrs = self.G.nodes[comp_id]

        # Prefer explicit value field, then fall back to part metadata.
        for key in ("value", "part_number", "part_type"):
            ohms = self._parse_ohms(attrs.get(key))
            if ohms is not None:
                return ohms

        return None

    def _is_short_resistor(self, comp_id: str, max_ohms: float) -> bool:
        """
        Determine whether a resistor should be treated as a conductive bridge.

        Design intent:
        - During differential-domain overlap checks, only low-value resistors, such as 0R jumpers,
          are treated as shorting paths.
        - Termination resistors, such as 120R, should not trigger false domain-overlap reports.
        """
        rv = self._component_resistance_ohms(comp_id)
        if rv is None:
            # Unknown resistor value is treated as non-short for overlap checks.
            return False
        return rv <= max_ohms + 1e-12

    def _check_not_floating(self, pin_node: str) -> bool:
        return len(self._pin_connected_nets(pin_node)) > 0

    @classmethod
    def classify_rule_graph_mode(cls, rule_type: str, params: Optional[Dict] = None) -> Literal["A", "B", "C"]:
        """
        Classify a rule into one of the three basic graph traversal modes: A/B/C.

        Special case:
        - REQUIRE_PROGRAMMING_RESISTOR defaults to B.
        - It is promoted to C when parameters explicitly require voltage-domain or cross-module propagation checks.
        """
        params = params or {}
        default_mode = cls.RULE_GRAPH_MODE.get(str(rule_type), "A")

        if str(rule_type) == "REQUIRE_PROGRAMMING_RESISTOR":
            needs_domain_propagation = bool(
                params.get("check_voltage_domain")
                or params.get("domain_propagation")
                or params.get("cross_module")
                or params.get("global_scope")
                or params.get("voltage_constraint")
            )
            if needs_domain_propagation:
                return "C"

        return "A" if default_mode == "A" else ("B" if default_mode == "B" else "C")

    @classmethod
    def is_local_rule(cls, rule: Dict) -> bool:
        """
        Local-stage rules: A + B.
        """
        rule_type = str(rule.get("rule_type", ""))
        params = rule.get("parameters", {}) if isinstance(rule.get("parameters", {}), dict) else {}
        return cls.classify_rule_graph_mode(rule_type, params) in {"A", "B"}

    @classmethod
    def is_global_rule(cls, rule: Dict) -> bool:
        """
        Global-stage rules: C.
        """
        rule_type = str(rule.get("rule_type", ""))
        params = rule.get("parameters", {}) if isinstance(rule.get("parameters", {}), dict) else {}
        return cls.classify_rule_graph_mode(rule_type, params) == "C"

    def _resolve_rule_severity(self, rule_type: str, rule: Dict) -> Literal["error", "warning"]:
        """
        Resolve rule severity.

        Priority:
        1) rule.severity.
        2) rule.parameters.severity.
        3) Built-in default mapping.
        """
        raw = str(rule.get("severity", rule.get("parameters", {}).get("severity", ""))).strip().lower()
        if raw in {"error", "fatal", "hard"}:
            return "error"
        if raw in {"warning", "warn", "soft"}:
            return "warning"

        mapped = self.DEFAULT_RULE_SEVERITY.get(rule_type, "warning").strip().lower()
        return "error" if mapped == "error" else "warning"

    def verify_pin_multiplexing(self, comp_id: str) -> List[ERCIssue]:
        """
        Structural hard rule: check whether a pin is connected to multiple different nets.
        This is an illegal topology short and should be reported as a severe error to the model.
        """
        issues = []
        for pin in self._component_pins(comp_id):
            nets = self._pin_connected_nets(pin)
            if len(nets) > 1:
                pin_name = self.G.nodes[pin].get("name", str(pin))
                issues.append(
                    ERCIssue(
                        rule_type="PIN_MULTIPLEXING_ERROR",
                        target=comp_id,
                        severity="error",
                        message=f"Pin '{pin_name}' is illegally connected to multiple nets simultaneously: {nets}. A physical pin cannot connect directly to multiple distinct net names."
                    )
                )
        return issues

    # ============================================================
    # Rule dispatch
    # ============================================================
    def verify_rule(self, comp_id: str, rule: dict) -> List[ERCIssue]:
        """
        Rule dispatcher.

        Design goals:
        1) Expose a single unified entry point to callers, so they do not need to know individual checkers.
        2) Keep a one-rule-to-one-checker mapping for easier extension and unit testing.
        3) Convert all exceptions into readable errors instead of interrupting the ERC loop.
        4) Return structured issues with severity so hard/soft violations can be separated.

        Return convention:
        - [] means passed.
        - [ERCIssue] means a violation or engine error was found.
        """
        rule_type = rule.get("rule_type")
        params = rule.get("parameters", {})
        description = rule.get("description", "No description provided.")
        severity = self._resolve_rule_severity(rule_type, rule)

        if rule_type in self.RETIRED_RULE_TYPES:
            logging.info(f"Retired rule type skipped: {rule_type}")
            return []

        handlers = {
            "REQUIRE_BYPASS_CAP": self._check_bypass_cap,
            "REQUIRE_PULL_UP_DOWN": self._check_pull_up_down,
            "REQUIRE_SERIES_PASSIVE": self._check_series_passive,
            "REQUIRE_RESONATOR": self._check_resonator,
            "FORBID_FLOATING": self._check_forbid_floating,
            "MANDATORY_NET_CONNECTION": self._check_mandatory_net_connection,
            "FORBIDDEN_CONNECTION": self._check_forbidden_connection,
            "VOLTAGE_DOMAIN_MATCH": self._check_voltage_domain_match,
            "GROUND_SEPARATION": self._check_ground_separation,
            "DIFFERENTIAL_PAIR": self._check_differential_pair,
            "REQUIRE_FEEDBACK_NETWORK": self._check_feedback_network,
            "REQUIRE_SENSE_RESISTOR": self._check_sense_resistor,
            "REQUIRE_PROGRAMMING_RESISTOR": self._check_programming_resistor,
            "REQUIRE_BUS_TERMINATION": self._check_bus_termination,
            "REQUIRE_GATE_BASE_RESISTOR": self._check_gate_base_resistor,
            "REQUIRE_FREEWHEELING_DIODE": self._check_freewheeling_diode,
            "REQUIRE_CURRENT_LIMIT_RESISTOR": self._check_current_limit_resistor,
            "OPEN_DRAIN_OUTPUT_PULLUP": self._check_open_drain_output_pullup,
            "REQUIRE_AUDIO_STABILITY_NETWORK": self._check_audio_stability_network,
            "REQUIRE_OSC_LOAD_CAPS": self._check_osc_load_caps,
            "REQUIRE_PARALLEL_PROTECTION": self._check_parallel_protection,
            "REQUIRE_GAIN_SETTING_NETWORK": self._check_gain_setting_network,
            "REQUIRE_TIMING_NETWORK": self._check_timing_network,
        }

        if rule_type not in handlers:
            logging.warning(f"Unimplemented rule type: {rule_type}")
            return []

        try:
            success, msg = handlers[rule_type](comp_id, params)
        except Exception as e:
            return [
                {
                    "component_id": comp_id,
                    "rule_type": rule_type,
                    "severity": "error",
                    "kind": "engine_error",
                    "message": f"Rule '{rule_type}' raised exception: {e}",
                    "description": description,
                }
            ]

        if success:
            return []
        return [
            {
                "component_id": comp_id,
                "rule_type": rule_type,
                "severity": severity,
                "kind": "violation",
                "message": msg,
                "description": description,
            }
        ]

