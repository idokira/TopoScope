    def _check_bypass_cap(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_BYPASS_CAP: decoupling / bypass capacitor rule.

        Logic:
        1) Each target pin must first be connected to a Net; floating is not allowed.
        2) The Net must have a path from capacitor to the reference network.
        3) The reference network type is given by reference_pin_type and defaults to Ground.

        Notes:
        - This checks topology only and does not numerically match cap_values.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        ref = params.get("reference_pin_type", "Ground")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Pin '{p}' is floating, expected bypass capacitor."

            ok = False
            for n in nets:
                # Fix hidden issue 1: if the pin itself is on system ground or in a single-supply use case, pass.
                # However, for decoupling on a Power net, do not pass only because it is Power, unless the reference
                # is also Power.
                if self._is_net_type(n, ref):
                    ok = True
                    break
                if self._net_has_component_to_ref_net(n, "capacitor", ref):
                    ok = True
                    break

            if not ok:
                return False, f"Missing bypass capacitor from net of pin '{p}' to '{ref}'."

        return True, "Verification passed."

    def _check_pull_up_down(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_PULL_UP_DOWN: pull-up / pull-down resistor rule.

        Logic:
        1) The target pin must not be floating.
        2) The connected net must contain at least one resistor.
        3) The other side of the resistor must connect to Power for pull-up or Ground for pull-down.
        4) If a resistance range is provided, filter by range when the value can be parsed.

        Notes:
        - If the resistance value cannot be parsed, only the topology is checked to avoid over-rejection.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        pull_type = self._safe_lower(params.get("pull_type", "UP"))
        ref_type = "Power" if pull_type == "up" else "Ground"
        lo, hi = self._parse_range_ohms(params.get("resistor_value_range", "Any"))

        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Pin '{p}' is floating, expected {pull_type} resistor."

            found = False
            for net in nets:
                for r in self._resistors_on_net(net):
                    r_val = self._parse_ohms(self.G.nodes[r].get("value"))
                    if lo is not None and hi is not None and r_val is not None and not (lo <= r_val <= hi):
                        continue
                    for other_net in self._component_nets(r):
                        if other_net != net and self._is_net_type(other_net, ref_type):
                            found = True
                            break
                    if found:
                        break
                if found:
                    break

            if not found:
                return False, f"Missing {pull_type} resistor on pin '{p}' net to {ref_type}."

        return True, "Verification passed."

    def _check_series_passive(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_SERIES_PASSIVE: series passive component rule.

        Logic:
        1) The target pin must have a net connection.
        2) On that net, excluding the current IC, find a component of the specified passive_type.
        3) The component must connect at least two different Nets, so a parallel attachment is not mistaken
           for a series element.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        passive_type = params.get("passive_type", "Resistor")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Pin '{p}' is floating, expected series {passive_type}."

            match = False
            for net in nets:
                for c in self._components_on_net(net, exclude={comp_id}):
                    if self._component_matches_kind(c, passive_type):
                        # A series component should connect at least two different nets.
                        # These nets should not be Power/Ground unless explicitly allowed.
                        cnets = self._component_nets(c)
                        if len(cnets) >= 2:
                            # Fix hidden issue 2: exclude pull-up/decoupling components that actually go
                            # to power or ground.
                            power_gnd_count = sum(1 for n in cnets if self._is_net_type(n, "Power") or self._is_net_type(n, "Ground"))
                            is_inductor = self._safe_lower(passive_type) in {"inductor", "ferritebead"}
                            allow_pg = self._parse_bool_param(params.get("allow_power_ground"), False)

                            if power_gnd_count == 0 or is_inductor or allow_pg or power_gnd_count >= 2:
                                match = True
                                break
                if match:
                    break

            if not match:
                return False, f"Missing series {passive_type} on pin '{p}'."

        return True, "Verification passed."

    def _check_resonator(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_RESONATOR: crystal / resonator rule.

        Logic:
        1) pin_in and pin_out must exist and both connect to Nets.
        2) They must not be shorted to the same Net.
        3) There must be a resonator/crystal component bridging the two side Nets.
        4) If needs_load_caps=True, both IN/OUT side Nets must have a load-cap-to-Ground path.
        """
        pin_in = self._resolve_pin_node(comp_id, params.get("pin_in"))
        pin_out = self._resolve_pin_node(comp_id, params.get("pin_out"))
        needs_load_caps = bool(params.get("needs_load_caps", False))

        if not pin_in or not pin_out:
            return False, "Invalid parameters: pin_in/pin_out not found."

        nets_in = self._pin_connected_nets(pin_in)
        nets_out = self._pin_connected_nets(pin_out)
        if not nets_in or not nets_out:
            return False, "Resonator pins are floating."

        n_in = nets_in[0]
        n_out = nets_out[0]
        if n_in == n_out:
            return False, "pin_in and pin_out are shorted to same net."

        shared = set(self._components_on_net(n_in)).intersection(self._components_on_net(n_out))
        has_res = any(self._component_matches_kind(c, "resonator") for c in shared)
        if not has_res:
            return False, "Missing resonator/crystal bridging pin_in and pin_out nets."

        if needs_load_caps:
            if not self._net_has_component_to_ref_net(n_in, "capacitor", "Ground"):
                return False, "Missing load capacitor to Ground on pin_in net."
            if not self._net_has_component_to_ref_net(n_out, "capacitor", "Ground"):
                return False, "Missing load capacitor to Ground on pin_out net."

        return True, "Verification passed."

    def _check_forbid_floating(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        FORBID_FLOATING: forbid critical pins from floating.

        Logic:
        1) Target pins must resolve to real Pin nodes.
        2) active_condition=always means unconditional checking.
        3) For non-always conditions, use a heuristic "component active" check:
           if there are no signal connections other than power/ground, treat it as inactive and skip.
        4) Checked pins must connect to at least one Net.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        active_condition = self._safe_lower(params.get("active_condition", "always"))
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        if active_condition != "always":
            # Heuristic: if the component has no obvious signal wiring, bypass this conditional rule.
            all_pins = self._component_pins(comp_id)
            signal_net_count = 0
            for p in all_pins:
                for n in self._pin_connected_nets(p):
                    if not (self._is_net_type(n, "power") or self._is_net_type(n, "ground")):
                        signal_net_count += 1
            if signal_net_count == 0:
                return True, "Condition not met, check bypassed."

        for p in resolved:
            if not self._check_not_floating(p):
                return False, f"Pin '{p}' is strictly forbidden from floating."

        return True, "Verification passed."

    def _check_mandatory_net_connection(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        MANDATORY_NET_CONNECTION: enforce connection to a required net type.

        Logic:
        1) Each target pin must be connected and must not be floating.
        2) At least one connected Net must match required_net_type.
        3) This rule uses strict matching: it only checks the Net node's own attributes and name,
           and does not infer the net type backward from connected pin types.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        req = params.get("required_net_type", "")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."
        if not req:
            return False, "Rule parameter error: required_net_type is missing."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Pin '{p}' is floating but must connect to '{req}'."
            if not any(self._is_net_type_strict(n, req) for n in nets):
                return False, f"Pin '{p}' is not connected to required net type '{req}'."

        return True, "Verification passed."

    def _check_forbidden_connection(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        FORBIDDEN_CONNECTION: absolutely forbidden connection, typically for DNC pins.

        Logic:
        - If any target pin is connected to any Net, the rule fails.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        for p in resolved:
            if self._pin_connected_nets(p):
                return False, f"Pin '{p}' is DNC but has net connection(s)."

        return True, "Verification passed."

    def _check_voltage_domain_match(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        VOLTAGE_DOMAIN_MATCH: pin voltage tolerance / voltage-domain constraint.

        Logic:
        1) Extract a threshold voltage from voltage_constraint, such as <=5.5V.
        2) Check the voltage of each Net connected to each target pin.
        3) Net voltage is read from explicit voltage first, then parsed from the Net name, such as 3.3V.
        4) Report an error once an out-of-range voltage is found.

        Notes:
        - If the constraint cannot be parsed, skip the check by default to avoid blocking the flow
          with false positives.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Target pin(s) not found: {missing}."

        vmin, vmax, parse_ok = self._parse_absolute_voltage_constraint(params.get("voltage_constraint"))
        if not parse_ok:
            return True, "Unparsable voltage constraint, bypassed."
        if vmin is None and vmax is None:
            return True, "No voltage constraint, bypassed."

        bridge_kinds = self._resolve_propagation_bridge_kinds(params, self._default_propagation_bridge_kinds())
        hops = self._propagation_hops(params, "propagation_hops", 8)

        for p in resolved:
            seed_nets = self._pin_connected_nets(p)
            if not seed_nets:
                continue

            domain_nets = self._propagate_nets(
                seed_nets,
                max_hops=hops,
                bridge_kinds=bridge_kinds,
                exclude_components={comp_id},
            )

            for n in sorted(domain_nets):
                v = self._net_voltage(n)
                if v is None:
                    continue
                if vmax is not None and v > vmax + 1e-9:
                    return False, f"Pin '{p}' exceeds max voltage {vmax}V via propagated net '{n}' ({v}V)."
                if vmin is not None and v < vmin - 1e-9:
                    return False, f"Pin '{p}' below min voltage {vmin}V via propagated net '{n}' ({v}V)."

        return True, "Verification passed."

    def _check_ground_separation(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        GROUND_SEPARATION: analog/digital ground isolation.

        Logic:
        1) Collect the Net set connected to analog_gnd_pins.
        2) Collect the Net set connected to digital_gnd_pins.
        3) Support two modes:
           - strict_isolation: absolute isolation; no connectivity is allowed.
           - controlled_join: allow a controlled single-point join, such as 0R/net-tie/ferrite bead.
        """
        ag_pins = self._collect_param_pins(params, "analog_gnd_pins")
        dg_pins = self._collect_param_pins(params, "digital_gnd_pins")

        ag_nodes, miss_a = self._resolve_pin_list(comp_id, ag_pins)
        dg_nodes, miss_d = self._resolve_pin_list(comp_id, dg_pins)
        if miss_a or miss_d:
            return False, f"Ground pin(s) not found: {miss_a + miss_d}."

        ag_seed_nets: Set[str] = set()
        dg_seed_nets: Set[str] = set()
        for p in ag_nodes:
            ag_seed_nets.update(self._pin_connected_nets(p))
        for p in dg_nodes:
            dg_seed_nets.update(self._pin_connected_nets(p))

        mode = self._safe_lower(params.get("ground_separation_mode", params.get("mode", "strict_isolation")))
        if mode not in {"strict_isolation", "controlled_join"}:
            mode = "strict_isolation"

        if mode == "strict_isolation":
            bridge_kinds = self._resolve_propagation_bridge_kinds(params, set())
        else:
            # In controlled_join mode, first check direct same-net shorts without traversing any bridge components.
            bridge_kinds = set()

        hops = self._propagation_hops(params, "propagation_hops", 8)

        ag_domain = self._propagate_nets(
            ag_seed_nets,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
        )
        dg_domain = self._propagate_nets(
            dg_seed_nets,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
        )

        shared = ag_domain.intersection(dg_domain)
        if shared:
            return False, f"Analog and digital ground domains are directly shorted on nets {sorted(shared)}."

        if mode == "strict_isolation":
            return True, "Verification passed."

        allowed_join_kinds = self._parse_kind_set_param(
            params,
            "allowed_join_kinds",
            {"nettie", "resistor", "ferritebead"},
        )

        max_join_count_raw = params.get("max_join_count", 1)
        try:
            max_join_count = max(0, min(8, int(max_join_count_raw)))
        except Exception:
            max_join_count = 1

        max_join_res_raw = params.get("max_join_resistance_ohms")
        try:
            max_join_res_ohms = float(max_join_res_raw) if max_join_res_raw is not None else None
        except Exception:
            max_join_res_ohms = None

        join_hops = self._propagation_hops(params, "join_hops", max(4, max_join_count + 2))

        def _allowed_join_component_gate(comp: str) -> bool:
            kind = self._normalize_kind_token(self._infer_component_kind(comp))
            if kind != "resistor" or max_join_res_ohms is None:
                return True
            rv = self._component_resistance_ohms(comp)
            return rv is None or rv <= max_join_res_ohms + 1e-12

        allowed_min_join = self._min_bridge_count_between_net_sets(
            ag_seed_nets,
            dg_seed_nets,
            allowed_bridge_kinds=allowed_join_kinds,
            max_hops=join_hops,
            exclude_components={comp_id},
            component_gate=_allowed_join_component_gate,
        )

        candidate_join_kinds = self._parse_kind_set_param(
            params,
            "candidate_join_kinds",
            {"resistor", "ferritebead", "nettie", "jumper", "testpoint", "inductor"},
        )

        candidate_min_join = self._min_bridge_count_between_net_sets(
            ag_seed_nets,
            dg_seed_nets,
            allowed_bridge_kinds=candidate_join_kinds,
            max_hops=join_hops,
            exclude_components={comp_id},
            component_gate=None,
        )

        if candidate_min_join is None:
            # No connection path exists, so the domains are validly isolated.
            return True, "Verification passed."

        if allowed_min_join is None:
            return False, (
                "Ground domains are connected, but no path satisfies allowed_join_kinds "
                "and max_join_resistance_ohms constraints."
            )

        if allowed_min_join > max_join_count:
            return False, (
                f"Controlled ground join path needs {allowed_min_join} join element(s), "
                f"exceeds max_join_count={max_join_count}."
            )

        return True, "Verification passed."

    def _default_propagation_bridge_kinds(self) -> Set[str]:
        """
        Default bridge component types allowed for network-domain propagation.

        Notes:
        - To avoid treating active-IC internals as conductive paths, propagation only goes through
          passive/diode-like components by default.
        - Capacitors are not traversed by default, so decoupling paths are not mistaken for DC voltage-domain
          connectivity.
        """
        return {"resistor", "inductor", "ferritebead", "diode", "passive"}

    def _resolve_propagation_bridge_kinds(self, params: Dict, default_kinds: Set[str]) -> Set[str]:
        raw = params.get("propagation_bridge_kinds")
        if not raw:
            return {self._normalize_kind_token(v) for v in default_kinds if self._normalize_kind_token(v)}
        if isinstance(raw, list):
            values = [self._normalize_kind_token(x) for x in raw]
            return {v for v in values if v}
        if isinstance(raw, str):
            values = [self._normalize_kind_token(x) for x in re.split(r"[,;|]", raw)]
            return {v for v in values if v}
        return {self._normalize_kind_token(v) for v in default_kinds if self._normalize_kind_token(v)}

    def _propagation_hops(self, params: Dict, key: str, default_hops: int) -> int:
        raw = params.get(key, default_hops)
        try:
            hops = int(raw)
            return max(0, min(hops, 32))
        except Exception:
            return default_hops

    def _is_bridge_component(self, comp_id: str, bridge_kinds: Set[str]) -> bool:
        kind = self._normalize_kind_token(self._infer_component_kind(comp_id))
        normalized_bridge_kinds = {self._normalize_kind_token(k) for k in bridge_kinds if self._normalize_kind_token(k)}
        return kind in normalized_bridge_kinds

    def _propagate_nets(
        self,
        seed_nets: Iterable[str],
        *,
        max_hops: int,
        bridge_kinds: Set[str],
        exclude_components: Optional[Set[str]] = None,
        terminal_net_types: Optional[Set[str]] = None,
        component_gate: Optional[Callable[[str], bool]] = None,
    ) -> Set[str]:
        """
        Run constrained BFS from seed nets and return the propagated network-domain set.
        """
        exclude_components = exclude_components or set()

        visited: Set[str] = set()
        queue: deque[Tuple[str, int]] = deque()
        for net in seed_nets:
            if self.G.has_node(net) and self.G.nodes[net].get("type") == "Net":
                visited.add(net)
                queue.append((net, 0))

        while queue:
            current_net, depth = queue.popleft()
            if depth >= max_hops:
                continue

            if terminal_net_types and any(self._is_net_type(current_net, t) for t in terminal_net_types):
                continue

            for comp in self._components_on_net(current_net, exclude=exclude_components):
                if not self._is_bridge_component(comp, bridge_kinds):
                    continue
                if component_gate is not None and not component_gate(comp):
                    continue

                for next_net in self._component_nets(comp):
                    if next_net in visited:
                        continue
                    visited.add(next_net)
                    queue.append((next_net, depth + 1))

        return visited

    def _domain_signature(self, nets: Set[str], exclude_comp: Optional[str] = None) -> Dict[str, int]:
        """
        Count component-kind distribution in a propagated domain for topology-symmetry comparison.
        """
        seen: Set[str] = set()
        sig: Dict[str, int] = {}
        for net in nets:
            for comp in self._components_on_net(net, exclude={exclude_comp} if exclude_comp else None):
                if comp in seen:
                    continue
                seen.add(comp)
                kind = self._infer_component_kind(comp)
                sig[kind] = sig.get(kind, 0) + 1
        return sig

    def _find_resistors_between_domains(self, domain_a: Set[str], domain_b: Set[str]) -> List[str]:
        """
        Search for resistors that bridge two propagated domains.
        """
        result: List[str] = []
        seen: Set[str] = set()

        for net in domain_a:
            for comp in self._resistors_on_net(net):
                if comp in seen:
                    continue
                c_nets = self._component_nets(comp)
                if c_nets.intersection(domain_a) and c_nets.intersection(domain_b):
                    seen.add(comp)
                    result.append(comp)

        return result

    def _check_differential_pair(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        DIFFERENTIAL_PAIR: differential-pair topology consistency.

        Logic:
        1) Positive and negative pins must both exist and have consistent connection states:
           one side cannot be connected while the other is floating.
        2) The two pins must not be shorted to the same Net.
        3) Compare the load signature of the two side Nets, namely component-kind counts, and require symmetry.

        Notes:
        - This does not check trace length or impedance. It focuses on schematic-level topology symmetry.
        """
        p = self._resolve_pin_node(comp_id, params.get("positive_pin"))
        n = self._resolve_pin_node(comp_id, params.get("negative_pin"))
        if not p or not n:
            return False, "Differential pins not found."

        p_nets = self._pin_connected_nets(p)
        n_nets = self._pin_connected_nets(n)
        if not p_nets and not n_nets:
            return True, "Both differential pins floating, bypassed."
        if not p_nets or not n_nets:
            return False, "One differential pin connected while the other is floating."

        pn = p_nets[0]
        nn = n_nets[0]
        if pn == nn:
            return False, "Differential pair shorted to same net."

        bridge_kinds = self._resolve_propagation_bridge_kinds(params, self._default_propagation_bridge_kinds())
        hops = self._propagation_hops(params, "propagation_hops", 4)
        allow_overlap = bool(params.get("allow_common_mode_overlap", False))

        # Differential-overlap propagation policy:
        # only low-ohm resistors are considered conductive bridges.
        try:
            overlap_resistor_max_ohms = float(
                params.get("overlap_resistor_max_ohms", params.get("short_resistor_max_ohms", 10.0))
            )
        except Exception:
            overlap_resistor_max_ohms = 10.0
        if overlap_resistor_max_ohms < 0:
            overlap_resistor_max_ohms = 0.0

        def _diff_component_gate(comp: str) -> bool:
            kind = self._safe_lower(self._infer_component_kind(comp))
            if kind == "resistor":
                return self._is_short_resistor(comp, overlap_resistor_max_ohms)
            return True

        p_domain = self._propagate_nets(
            p_nets,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
            terminal_net_types={"ground", "power"},
            component_gate=_diff_component_gate,
        )
        n_domain = self._propagate_nets(
            n_nets,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
            terminal_net_types={"ground", "power"},
            component_gate=_diff_component_gate,
        )

        overlap = p_domain.intersection(n_domain)
        meaningful_overlap = {
            n
            for n in overlap
            if not self._is_net_type(n, "ground") and not self._is_net_type(n, "power")
        }
        if meaningful_overlap and not allow_overlap:
            return False, f"Differential domains overlap on propagated nets {sorted(meaningful_overlap)}."

        p_sig = self._domain_signature(p_domain, exclude_comp=comp_id)
        n_sig = self._domain_signature(n_domain, exclude_comp=comp_id)

        compare_kinds = self._parse_kind_set_param(
            params,
            "compare_component_kinds",
            {"resistor", "capacitor", "inductor", "ferritebead"},
        )
        ignore_kinds = self._parse_kind_set_param(
            params,
            "ignore_component_kinds",
            {"diode", "testpoint", "jumper"},
        )
        required_common = self._parse_kind_set_param(params, "required_common_elements", set())

        tolerance_raw = params.get("symmetry_tolerance", 1)
        try:
            symmetry_tolerance = max(0, min(16, int(tolerance_raw)))
        except Exception:
            symmetry_tolerance = 1

        p_core: Dict[str, int] = {}
        n_core: Dict[str, int] = {}
        for k, v in p_sig.items():
            nk = self._normalize_kind_token(k)
            if nk in ignore_kinds or nk not in compare_kinds:
                continue
            p_core[nk] = p_core.get(nk, 0) + int(v)
        for k, v in n_sig.items():
            nk = self._normalize_kind_token(k)
            if nk in ignore_kinds or nk not in compare_kinds:
                continue
            n_core[nk] = n_core.get(nk, 0) + int(v)

        for req in required_common:
            if p_core.get(req, 0) <= 0 or n_core.get(req, 0) <= 0:
                return False, f"Missing required common differential element '{req}' on one side."

        mismatch: Dict[str, Tuple[int, int]] = {}
        for kind in sorted(set(p_core.keys()).union(n_core.keys())):
            pv = p_core.get(kind, 0)
            nv = n_core.get(kind, 0)
            if abs(pv - nv) > symmetry_tolerance:
                mismatch[kind] = (pv, nv)

        if mismatch:
            return False, (
                "Differential pair core signature exceeds symmetry_tolerance "
                f"({symmetry_tolerance}): {mismatch}"
            )

        return True, "Verification passed."

    def _check_feedback_network(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_FEEDBACK_NETWORK: feedback divider network, such as Buck/LDO FB.

        Logic:
        1) fb_pin must not be floating.
        2) Check two constrained feedback paths:
           - FB -> must traverse a resistor -> output domain.
           - FB -> must traverse a resistor -> ground domain.
        3) Allow a small set of transparent bridge elements, such as 0R/ferrite bead/net-tie/testpoint.
        4) If strict_direct_attach=True, fall back to the strict local divider mode where FB directly hosts
           the divider branches.
        """
        fb_pin = self._resolve_pin_node(comp_id, params.get("fb_pin"))
        vout_type = params.get("vout_net_type", "PowerOut")
        gnd_type = params.get("gnd_net_type", "Ground")
        strict_direct_attach = self._parse_bool_param(params.get("strict_direct_attach"), False)
        max_hops = self._propagation_hops(params, "max_feedback_hops", 6)

        allow_series_bridge_kinds = self._parse_kind_set_param(
            params,
            "allow_series_bridge_kinds",
            {"resistor", "ferritebead", "nettie", "testpoint", "jumper"},
        )
        allow_series_bridge_kinds.add("resistor")

        if not fb_pin:
            return False, "Feedback pin not found."

        fb_nets = self._pin_connected_nets(fb_pin)
        if not fb_nets:
            return False, "Feedback pin is floating."

        if strict_direct_attach:
            top_ok = False
            bot_ok = False
            for fb_net in fb_nets:
                for r in self._resistors_on_net(fb_net):
                    for n in self._component_nets(r):
                        if n == fb_net:
                            continue
                        if self._net_matches_reference(n, gnd_type):
                            bot_ok = True
                        if self._net_matches_reference(n, vout_type) or self._is_net_type(n, "power"):
                            top_ok = True
                if top_ok and bot_ok:
                    break

            if not (top_ok and bot_ok):
                return False, "Feedback divider topology mismatch to VOUT/GND under strict_direct_attach mode."
            return True, "Verification passed."

        top_ok = self._has_path_with_required_bridge(
            fb_nets,
            target_predicate=lambda n: self._net_matches_reference(n, vout_type) or self._is_net_type(n, "power"),
            max_hops=max_hops,
            allowed_bridge_kinds=allow_series_bridge_kinds,
            required_bridge_kinds={"resistor"},
            exclude_components={comp_id},
        )
        bot_ok = self._has_path_with_required_bridge(
            fb_nets,
            target_predicate=lambda n: self._net_matches_reference(n, gnd_type),
            max_hops=max_hops,
            allowed_bridge_kinds=allow_series_bridge_kinds,
            required_bridge_kinds={"resistor"},
            exclude_components={comp_id},
        )

        if not top_ok or not bot_ok:
            return False, "Feedback network missing constrained resistor path(s) to output/ground domains."

        return True, "Verification passed."

    def _check_sense_resistor(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_SENSE_RESISTOR: current-sense resistor rule.

        Logic:
        1) Sense pins must not be floating.
        2) Use bounded-hop topology search to locate a valid sense resistor in the sensing path.
        3) Support single-ended and differential modes:
           - single_ended: find a sense resistor and verify that it reaches a reference domain,
             such as ground/return/opposite sense.
           - differential: two sense pins should clamp across the same sense resistor.
        4) max_resistor_value can restrict the maximum value of the sense resistor.
        """
        pins = self._collect_param_pins(params, "sense_pins", "target_pins")
        max_r = self._parse_ohms(params.get("max_resistor_value"))
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Sense pin(s) not found: {missing}."

        mode = self._safe_lower(params.get("sense_mode", ""))
        if mode not in {"single_ended", "differential"}:
            mode = "differential" if len(resolved) >= 2 else "single_ended"

        hops = self._propagation_hops(params, "max_series_filter_hops", 3)
        allow_filter_components = self._parse_kind_set_param(
            params,
            "allow_filter_components",
            {"resistor", "capacitor", "nettie", "testpoint", "jumper", "ferritebead"},
        )
        allow_filter_components.add("resistor")

        sense_reference = self._safe_lower(params.get("sense_reference", ""))
        if not sense_reference:
            sense_reference = "opposite_sense_pin" if mode == "differential" else "return"

        def _domain_and_candidate_resistors(seed_nets: Iterable[str]) -> Tuple[Set[str], Set[str]]:
            domain = self._propagate_nets(
                seed_nets,
                max_hops=hops,
                bridge_kinds=allow_filter_components,
                exclude_components={comp_id},
            )
            resistors: Set[str] = set()
            for net in domain:
                for r in self._resistors_on_net(net):
                    rv = self._parse_ohms(self.G.nodes[r].get("value"))
                    if max_r is not None and rv is not None and rv > max_r:
                        continue
                    resistors.add(r)
            return domain, resistors

        def _resistor_reaches_reference(r: str, reference: str) -> bool:
            r_nets = self._component_nets(r)
            local_hops = max(1, min(hops, 3))
            for rn in r_nets:
                ref_domain = self._propagate_nets(
                    [rn],
                    max_hops=local_hops,
                    bridge_kinds=allow_filter_components,
                    exclude_components={comp_id},
                )
                if any(self._net_matches_reference(n, reference) for n in ref_domain):
                    return True
            return False

        if mode == "differential":
            if len(resolved) < 2:
                return False, "Differential sense mode requires at least two sense pins."

            p_pin, n_pin = resolved[0], resolved[1]
            p_nets = self._pin_connected_nets(p_pin)
            n_nets = self._pin_connected_nets(n_pin)
            if not p_nets or not n_nets:
                return False, "Differential sense pin pair has floating net(s)."

            _, p_res = _domain_and_candidate_resistors(p_nets)
            _, n_res = _domain_and_candidate_resistors(n_nets)
            shared = p_res.intersection(n_res)
            if not shared:
                return False, "Differential sense pin pair cannot clamp to the same valid sense resistor."

            if sense_reference not in {"", "opposite_sense_pin"}:
                if not any(_resistor_reaches_reference(r, sense_reference) for r in shared):
                    return False, f"Differential sense resistor found, but no path to reference '{sense_reference}'."

            return True, "Verification passed."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Sense pin '{p}' is floating."

            domain, resistors = _domain_and_candidate_resistors(nets)
            if not resistors:
                return False, f"Missing valid sense resistor in filtered sense path of pin '{p}'."

            ok = False
            if sense_reference == "opposite_sense_pin":
                opposite_seed: Set[str] = set()
                for op in resolved:
                    if op == p:
                        continue
                    opposite_seed.update(self._pin_connected_nets(op))
                opposite_domain, _ = _domain_and_candidate_resistors(opposite_seed)

                for r in resistors:
                    if self._component_nets(r).intersection(opposite_domain):
                        ok = True
                        break
            else:
                for r in resistors:
                    if _resistor_reaches_reference(r, sense_reference):
                        ok = True
                        break

            # If the reference is not explicitly given and the path reaches a valid resistor,
            # pass under the minimum-feasible principle.
            if not ok and not sense_reference:
                ok = bool(resistors)

            if not ok:
                return False, (
                    f"Sense pin '{p}' has resistor candidate(s) but none reaches reference '{sense_reference}'."
                )

        return True, "Verification passed."

    def _check_programming_resistor(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_PROGRAMMING_RESISTOR: programming / setting resistor rule.

        Logic:
        1) The prog pin must not be floating.
        2) The net connected to the prog pin must contain a resistor, and the resistor's other side
           must reach reference_net.
        3) value_formula is currently recorded for documentation only and is not numerically solved.
        """
        pins = self._collect_param_pins(params, "prog_pins", "target_pins")
        ref = params.get("reference_net", "Ground")
        needs_domain_propagation = bool(
            params.get("check_voltage_domain")
            or params.get("domain_propagation")
            or params.get("cross_module")
            or params.get("global_scope")
            or params.get("voltage_constraint")
        )

        _, vmax, _ = self._parse_absolute_voltage_constraint(params.get("voltage_constraint"))

        bridge_kinds = self._resolve_propagation_bridge_kinds(params, self._default_propagation_bridge_kinds())
        hops = self._propagation_hops(params, "propagation_hops", 8)

        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Programming pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Programming pin '{p}' is floating."

            ok = any(self._net_has_component_to_ref_net(n, "resistor", ref) for n in nets)
            if not ok:
                return False, f"Missing programming resistor from '{p}' net to '{ref}'."

            if needs_domain_propagation:
                domain = self._propagate_nets(
                    nets,
                    max_hops=hops,
                    bridge_kinds=bridge_kinds,
                    exclude_components={comp_id},
                )

                if ref and not any(self._is_net_type(n, ref) for n in domain):
                    return False, f"Programming domain of pin '{p}' cannot reach reference net type '{ref}'."

                if vmax is not None:
                    for n in sorted(domain):
                        v = self._net_voltage(n)
                        if v is not None and v > vmax + 1e-9:
                            return False, f"Programming domain of pin '{p}' exceeds {vmax}V on net '{n}' ({v}V)."

        return True, "Verification passed."

    def _check_bus_termination(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_BUS_TERMINATION: bus termination resistor rule.

        Logic:
        1) bus_pin_a / bus_pin_b must exist and each must connect to a net.
        2) They must not be shorted to the same Net.
        3) There must be a resistor connecting the two side Nets.
        4) If termination_value is provided, match it with ±20% tolerance.
        """
        pa = self._resolve_pin_node(comp_id, params.get("bus_pin_a"))
        pb = self._resolve_pin_node(comp_id, params.get("bus_pin_b"))
        term_value = self._parse_ohms(params.get("termination_value"))

        if not pa or not pb:
            return False, "Bus pins not found."

        na = self._pin_connected_nets(pa)
        nb = self._pin_connected_nets(pb)
        if not na or not nb:
            return False, "Bus pins are floating."

        if set(na).intersection(set(nb)):
            return False, "Bus A/B are shorted to same net."

        bridge_kinds = self._resolve_propagation_bridge_kinds(params, self._default_propagation_bridge_kinds())
        hops = self._propagation_hops(params, "propagation_hops", 6)
        domain_a = self._propagate_nets(
            na,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
        )
        domain_b = self._propagate_nets(
            nb,
            max_hops=hops,
            bridge_kinds=bridge_kinds,
            exclude_components={comp_id},
        )

        terms = self._find_resistors_between_domains(domain_a, domain_b)
        if not terms:
            return False, "Missing termination resistor between bus A/B nets."

        if term_value is not None:
            matched_value = False
            for t in terms:
                rv = self._parse_ohms(self.G.nodes[t].get("value"))
                if rv is None or abs(rv - term_value) / max(term_value, 1e-9) <= 0.2:
                    matched_value = True
                    break
            if not matched_value:
                return False, "Termination resistor exists but value mismatches termination_value."

        return True, "Verification passed."

    def _check_gate_base_resistor(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_GATE_BASE_RESISTOR: gate/base current-limiting and termination rule.

        Logic:
        1) The control pin must not be floating.
        2) The control net should include at least one resistor.
        3) If needs_pull_down=True, a resistor path to Ground is required.
        """
        pins = self._collect_param_pins(params, "control_pins", "target_pins")
        needs_pull_down = bool(params.get("needs_pull_down", False))
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Control pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Control pin '{p}' is floating."

            net = nets[0]
            # Require at least one resistor to participate in the control network.
            if not self._resistors_on_net(net):
                return False, f"Missing gate/base resistor on control pin '{p}' net."

            if needs_pull_down:
                if not self._net_has_component_to_ref_net(net, "resistor", "Ground") and not self._is_net_type(net, "Ground"):
                    return False, f"Pin '{p}' requires pull-down but no resistor-to-ground found."

        return True, "Verification passed."

    def _check_freewheeling_diode(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_FREEWHEELING_DIODE: freewheeling diode rule.

        Logic:
        1) The drive pin must not be floating.
        2) A diode component must exist near the drive net.
        3) If diode_type is specified, the model/type text must contain the required keyword.
        4) The diode should provide a common freewheeling path to power or ground.
        """
        pins = self._collect_param_pins(params, "drive_pins", "target_pins")
        diode_type = self._safe_lower(params.get("diode_type", ""))
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Drive pin(s) not found: {missing}."

        def _normalize_text(raw: object) -> str:
            s = self._safe_lower(raw)
            s = s.replace("_", " ").replace("-", " ")
            return re.sub(r"\s+", " ", s).strip()

        def _diode_type_match(required: str, candidate_text: str) -> bool:
            """
            Match diode_type more robustly:
            - Support "A or B" forms.
            - Support parenthesized notes, such as trr constraints.
            - Support common part-number aliases, such as SSxx/MBRxx/BATxx/UFxx.
            """
            req = _normalize_text(required)
            cand = _normalize_text(candidate_text)
            if not req:
                return True
            if req in cand:
                return True

            schottky_patterns = [
                r"\bschottky\b",
                r"\bss\d+[a-z0-9]*\b",
                r"\bmbr\d+[a-z0-9]*\b",
                r"\bbat\d+[a-z0-9]*\b",
                r"\bsb\d+[a-z0-9]*\b",
            ]
            fast_recovery_patterns = [
                r"\bfast\s*recovery\b",
                r"\bultra\s*fast\b",
                r"\bfrd\b",
                r"\buf\d+[a-z0-9]*\b",
            ]

            alternatives = [x.strip() for x in re.split(r"\bor\b|\||/|,", req) if x.strip()]
            for alt in alternatives:
                alt = re.sub(r"\([^)]*\)", " ", alt)
                alt = re.sub(r"\s+", " ", alt).strip()
                if not alt:
                    continue
                if alt in cand:
                    return True

                if alt == "schottky":
                    if any(re.search(pat, cand) for pat in schottky_patterns):
                        return True
                    continue

                if "fast" in alt and "recover" in alt:
                    if any(re.search(pat, cand) for pat in fast_recovery_patterns):
                        return True
                    continue

                tokens = [
                    t
                    for t in re.findall(r"[a-z0-9]+", alt)
                    if t not in {"and", "or", "trr", "ns", "le", "lt", "ge", "gt"} and len(t) >= 3
                ]
                if tokens and all(t in cand for t in tokens):
                    return True

            # Fallback: pass if the mixed description still contains the key diode class.
            if "schottky" in req and any(re.search(pat, cand) for pat in schottky_patterns):
                return True
            if "fast" in req and "recover" in req and any(re.search(pat, cand) for pat in fast_recovery_patterns):
                return True

            return False

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Drive pin '{p}' is floating."

            found = False
            for n in nets:
                for c in self._components_on_net(n, exclude={comp_id}):
                    if not self._component_matches_kind(c, "diode"):
                        continue
                    if diode_type:
                        text = " ".join([
                            self._safe_lower(self.G.nodes[c].get("part_type")),
                            self._safe_lower(self.G.nodes[c].get("part_number")),
                            self._safe_lower(self.G.nodes[c].get("value")),
                            self._safe_lower(self.G.nodes[c].get("description")),
                            self._safe_lower(c),
                        ])
                        if not _diode_type_match(diode_type, text):
                            continue
                    # Common freewheeling path: the other side of the diode connects to power or ground.
                    if any(self._is_net_type(x, "power") or self._is_net_type(x, "ground") for x in self._component_nets(c)):
                        found = True
                        break
                if found:
                    break

            if not found:
                return False, f"Missing freewheeling diode near drive pin '{p}'."

        return True, "Verification passed."

    def _check_current_limit_resistor(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_CURRENT_LIMIT_RESISTOR: LED/opto current-limiting resistor rule.

        Logic:
        1) The specified anode/cathode pins must not be floating.
        2) The corresponding net should contain at least one resistor as the current-limiting element.

        Notes:
        - safe_current_range is not numerically solved yet; only topology existence is checked.
        """
        anodes = self._collect_param_pins(params, "anode_pins")
        cathodes = self._collect_param_pins(params, "cathode_pins")

        a_nodes, miss_a = self._resolve_pin_list(comp_id, anodes)
        c_nodes, miss_c = self._resolve_pin_list(comp_id, cathodes)
        if miss_a or miss_c:
            return False, f"LED/opto pin(s) not found: {miss_a + miss_c}."

        check_nodes = a_nodes + c_nodes
        for p in check_nodes:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Pin '{p}' is floating."
            if not any(self._resistors_on_net(n) for n in nets):
                return False, f"Missing current-limit resistor on net of pin '{p}'."

        return True, "Verification passed."

    def _check_open_drain_output_pullup(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        OPEN_DRAIN_OUTPUT_PULLUP: open-drain / open-collector output pull-up rule.

        Strategy:
        - First filter target pins that are actually used, meaning they have net connections.
        - Only run the pull-up check for these used pins.
        - Fully unused open-drain pins do not trigger false positives.
        - The concrete check reuses REQUIRE_PULL_UP_DOWN with pull_type=UP.
        """
        output_pins = self._collect_param_pins(params, "output_pins", "target_pins")

        resolved, missing = self._resolve_pin_list(comp_id, output_pins)
        if missing:
            return False, f"Open-drain pin(s) not found: {missing}."

        connected_pins = [p for p in resolved if self._pin_connected_nets(p)]
        if not connected_pins:
            return True, "All open-drain pins are unused (floating); pull-up check skipped."

        return self._check_pull_up_down(
            comp_id,
            {
                "target_pins": connected_pins,
                "pull_type": "UP",
                "resistor_value_range": params.get("resistor_value_range", "Any"),
            },
        )

    def _check_audio_stability_network(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_AUDIO_STABILITY_NETWORK: audio stability network, such as Zobel / AC coupling.

        Logic:
        1) Output pins must not be floating.
        2) Use stability-evidence patterns instead of a fixed datasheet-page shape:
           - zobel
           - snubber
           - series_isolation_load_cap
           - datasheet_optional
        3) If requires_ac_coupling=True, selectively check based on output topology;
           single_ended checks it by default.
        """
        pins = self._collect_param_pins(params, "output_pins", "target_pins")
        req_zobel = self._parse_bool_param(params.get("requires_zobel"), True)
        req_ac = self._parse_bool_param(params.get("requires_ac_coupling"), False)
        require_stability_evidence = self._parse_bool_param(params.get("require_stability_evidence"), False)
        output_topology = self._safe_lower(params.get("output_topology", "single_ended"))
        if output_topology not in {"single_ended", "btl", "filterless"}:
            output_topology = "single_ended"

        def _normalize_stability_pattern(raw: object) -> str:
            token = self._safe_lower(raw).replace("-", "_").replace(" ", "_")
            token = re.sub(r"_+", "_", token).strip("_")
            compact = token.replace("_", "")
            aliases = {
                "zobel": "zobel",
                "snubber": "snubber",
                "seriesisolationloadcap": "seriesisolationloadcap",
                "seriesisolationloadc": "seriesisolationloadcap",
                "seriesisolationplusloadcap": "seriesisolationloadcap",
                "datasheetoptional": "datasheetoptional",
            }
            return aliases.get(compact, compact)

        def _parse_stability_patterns(raw: object) -> Set[str]:
            if raw is None:
                return set()
            values: List[str]
            if isinstance(raw, list):
                values = [str(v) for v in raw]
            elif isinstance(raw, str):
                values = re.split(r"[,;|]", raw)
            else:
                return set()
            out = {_normalize_stability_pattern(v) for v in values if str(v).strip()}
            return {v for v in out if v in {"zobel", "snubber", "seriesisolationloadcap", "datasheetoptional"}}

        allowed_patterns = _parse_stability_patterns(params.get("allowed_stability_patterns"))
        if not allowed_patterns:
            allowed_patterns = _parse_stability_patterns(params.get("stability_evidence"))
        if not allowed_patterns:
            allowed_patterns = {"zobel", "snubber", "seriesisolationloadcap", "datasheetoptional"}

        def _has_zobel_like(output_net: str, comps: Set[str]) -> bool:
            for c1 in comps:
                kind1 = (
                    "resistor"
                    if self._component_matches_kind(c1, "resistor")
                    else "capacitor"
                    if self._component_matches_kind(c1, "capacitor")
                    else None
                )
                if not kind1:
                    continue
                target_kind2 = "capacitor" if kind1 == "resistor" else "resistor"
                for mid_net in self._component_nets(c1):
                    if mid_net == output_net or self._is_net_type(mid_net, "ground"):
                        continue
                    for c2 in self._components_on_net(mid_net, exclude={c1}):
                        if not self._component_matches_kind(c2, target_kind2):
                            continue
                        c2_nets = self._component_nets(c2)
                        if any(self._is_net_type(n2, "ground") for n2 in c2_nets if n2 != mid_net):
                            return True
            return False

        def _has_snubber_like(output_net: str, comps: Set[str]) -> bool:
            for c1 in comps:
                kind1 = (
                    "resistor"
                    if self._component_matches_kind(c1, "resistor")
                    else "capacitor"
                    if self._component_matches_kind(c1, "capacitor")
                    else None
                )
                if not kind1:
                    continue
                target_kind2 = "capacitor" if kind1 == "resistor" else "resistor"
                for mid_net in self._component_nets(c1):
                    if mid_net == output_net:
                        continue
                    for c2 in self._components_on_net(mid_net, exclude={c1}):
                        if not self._component_matches_kind(c2, target_kind2):
                            continue
                        c2_nets = self._component_nets(c2)
                        if any(
                            (self._is_net_type(n2, "ground") or self._is_net_type(n2, "power"))
                            for n2 in c2_nets
                            if n2 != mid_net
                        ):
                            return True
            return False

        def _has_series_isolation_load_cap(output_net: str, comps: Set[str]) -> bool:
            for c in comps:
                if not (
                    self._component_matches_kind(c, "resistor")
                    or self._component_matches_kind(c, "inductor")
                    or self._component_matches_kind(c, "ferritebead")
                ):
                    continue
                for next_net in self._component_nets(c):
                    if next_net == output_net:
                        continue
                    if self._is_net_type(next_net, "ground") or self._is_net_type(next_net, "power"):
                        continue
                    if self._net_has_component_to_ref_net(next_net, "capacitor", "ground"):
                        return True
            return False

        def _has_ac_coupling(output_net: str, comps: Set[str]) -> bool:
            for c in comps:
                if not self._component_matches_kind(c, "capacitor"):
                    continue
                cnets = self._component_nets(c)
                if output_net in cnets and any((n != output_net and not self._is_net_type(n, "ground")) for n in cnets):
                    return True
            return False

        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Audio output pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Audio output pin '{p}' is floating."

            net = nets[0]
            comps = self._components_on_net(net, exclude={comp_id})

            evidence: Set[str] = set()
            if _has_zobel_like(net, comps):
                evidence.add("zobel")
            if _has_snubber_like(net, comps):
                evidence.add("snubber")
            if _has_series_isolation_load_cap(net, comps):
                evidence.add("seriesisolationloadcap")
            if _has_ac_coupling(net, comps):
                evidence.add("ac_coupling")

            enforce_ac = req_ac
            if output_topology in {"btl", "filterless"}:
                enforce_ac = self._parse_bool_param(params.get("force_ac_coupling"), False)
            if enforce_ac and "ac_coupling" not in evidence:
                return False, f"Missing AC coupling capacitor on audio output pin '{p}'."

            if req_zobel or require_stability_evidence:
                acceptable = allowed_patterns.intersection({"zobel", "snubber", "seriesisolationloadcap"})
                if not acceptable:
                    acceptable = {"zobel", "snubber", "seriesisolationloadcap"}
                if not evidence.intersection(acceptable):
                    if "datasheetoptional" not in allowed_patterns:
                        return False, (
                            f"Missing acceptable stability evidence on audio output pin '{p}'. "
                            f"Accepted patterns: {sorted(acceptable)}"
                        )

        return True, "Verification passed."

    def _check_osc_load_caps(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_OSC_LOAD_CAPS: oscillator load capacitor rule.

        Logic:
        1) If an external crystal is not required and unused floating pins are allowed, pass directly.
        2) When an external crystal is required, both oscillator pins must exist and connect to Nets.
        3) Both side Nets should have a capacitor-to-Ground path.
        """
        external_required = self._parse_bool_param(
            params.get("external_crystal_required", params.get("required")),
            False,
        )

        allow_unused_floating = self._parse_bool_param(
            params.get("allow_unused_floating"),
            not external_required,
        )

        if not external_required and allow_unused_floating:
            return True, "External oscillator not required; OSC-capable pins may remain unused."

        pin_candidates = self._collect_param_pins(
            params,
            "pin_1",
            "pin_2",
            "pin_in",
            "pin_out",
            "xtal_in",
            "xtal_out",
            "target_pins",
            "target_pin",
        )

        resolved, missing = self._resolve_pin_list(comp_id, pin_candidates)
        osc_pins: List[str] = []
        for pin in resolved:
            if pin not in osc_pins:
                osc_pins.append(pin)

        if len(osc_pins) < 2:
            for pin in self._component_pins(comp_id):
                pin_name = self._safe_lower(self.G.nodes[pin].get("name", ""))
                if any(tok in pin_name for tok in ["osc", "xtal", "xin", "xout"]):
                    if pin not in osc_pins:
                        osc_pins.append(pin)
                if len(osc_pins) >= 2:
                    break

        if len(osc_pins) < 2:
            detail = missing if missing else [str(x) for x in pin_candidates]
            return False, f"OSC pins not found from params: {detail}."

        for p in osc_pins[:2]:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"OSC pin '{p}' is floating."
            if not any(self._net_has_component_to_ref_net(n, "capacitor", "Ground") for n in nets):
                return False, f"Missing load capacitor to ground on OSC pin '{p}' net."

        return True, "Verification passed."

    def _check_parallel_protection(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_PARALLEL_PROTECTION: parallel interface protection, such as TVS/ESD.

        Logic:
        1) The target pin must not be floating.
        2) Its net should contain a protection component matching the protection_type keyword.
        3) If protection_type is not specified, match default protection features such as TVS/ESD/clamp/diode.
        4) The protection component must provide a discharge path to reference_net.
        """
        pins = self._collect_param_pins(params, "target_pins", "target_pin")
        protection_type = self._safe_lower(params.get("protection_type", ""))
        ref = params.get("reference_net", "Ground")

        default_protection_keywords = {"tvs", "esd", "clamp", "protect", "transorb", "diode"}

        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Protected interface pin(s) not found: {missing}."

        for p in resolved:
            nets = self._pin_connected_nets(p)
            if not nets:
                return False, f"Interface pin '{p}' is floating."

            found = False
            for n in nets:
                for c in self._components_on_net(n, exclude={comp_id}):
                    txt = " ".join([
                        self._infer_component_kind(c),
                        self._safe_lower(self.G.nodes[c].get("part_type")),
                        self._safe_lower(self.G.nodes[c].get("part_number")),
                        self._safe_lower(c),
                    ])
                    if protection_type:
                        if protection_type not in txt:
                            continue
                    else:
                        if not any(k in txt for k in default_protection_keywords):
                            continue
                    if any(self._is_net_type(nn, ref) for nn in self._component_nets(c) if nn != n):
                        found = True
                        break
                if found:
                    break

            if not found:
                return False, f"Missing parallel protection ({protection_type or 'TVS/ESD'}) on pin '{p}' net to '{ref}'."

        return True, "Verification passed."

    def _check_gain_setting_network(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_GAIN_SETTING_NETWORK: gain-setting network rule.

        Logic:
        A) RG/GAIN pin-pair mode, for instrumentation amplifiers or explicit gain_pin_1/gain_pin_2:
           1) gain_pin_1 / gain_pin_2 must exist and connect to nets.
           2) They must not be shorted to the same Net.
           3) By default, a resistor-reachable path between both sides is required; this can be overridden
              through requires_resistor.

        B) Classic op-amp feedback mode, as backward-compatible fallback:
           1) IN-/IN+/OUT pins must exist and connect to nets.
           2) There must be a feedback resistor between OUT and IN-.
           3) IN- should also have a second resistor branch to another reference net, forming a configurable
              gain network.

        Notes:
        - gain_formula is currently used only for documentation tracking and is not evaluated.
        """
        def _resolve_first_alias(candidates: List[str]) -> Optional[str]:
            for token in candidates:
                pin = self._resolve_pin_node(comp_id, token)
                if pin:
                    return pin
            return None

        gain_mode = self._safe_lower(params.get("gain_mode", "auto"))
        if gain_mode not in {"auto", "rg_pair", "opamp_feedback"}:
            gain_mode = "auto"

        # ------------------------------------------------------------
        # Mode A: RG/GAIN pin pair, such as INA128 RG_1 / RG_2.
        # ------------------------------------------------------------
        gain_pin_1 = self._resolve_pin_node(comp_id, params.get("gain_pin_1") or params.get("rg_pin_1"))
        gain_pin_2 = self._resolve_pin_node(comp_id, params.get("gain_pin_2") or params.get("rg_pin_2"))

        if not gain_pin_1:
            gain_pin_1 = _resolve_first_alias(["RG_1", "RG1", "GAIN_1", "GAIN1"])
        if not gain_pin_2:
            gain_pin_2 = _resolve_first_alias(["RG_2", "RG2", "GAIN_2", "GAIN2"])

        attrs_for_mode = self.G.nodes[comp_id] if self.G.has_node(comp_id) else {}
        comp_text_for_mode = " ".join(
            [
                self._safe_lower(comp_id),
                self._safe_lower(attrs_for_mode.get("part_type")),
                self._safe_lower(attrs_for_mode.get("part_number")),
            ]
        )

        gain_name_pair_for_mode: Set[str] = set()
        if gain_pin_1 and self.G.has_node(gain_pin_1):
            gain_name_pair_for_mode.add(self._safe_lower(self.G.nodes[gain_pin_1].get("name")))
        if gain_pin_2 and self.G.has_node(gain_pin_2):
            gain_name_pair_for_mode.add(self._safe_lower(self.G.nodes[gain_pin_2].get("name")))
        has_rg_naming_for_mode = any("rg" in n for n in gain_name_pair_for_mode if n)
        is_instrumentation_amp_for_mode = (
            ("instrument" in comp_text_for_mode)
            or ("in-amp" in comp_text_for_mode)
            or bool(re.search(r"\bina\d+", comp_text_for_mode))
            or has_rg_naming_for_mode
        )

        explicit_opamp_feedback = bool(params.get("in_minus_pin") or params.get("in_plus_pin") or params.get("out_pin"))
        explicit_rg_pair = bool(
            params.get("gain_pin_1")
            or params.get("gain_pin_2")
            or params.get("rg_pin_1")
            or params.get("rg_pin_2")
        )

        use_rg_pair_mode = False
        if gain_mode == "rg_pair":
            use_rg_pair_mode = True
        elif gain_mode == "opamp_feedback":
            use_rg_pair_mode = False
        else:
            if explicit_opamp_feedback:
                use_rg_pair_mode = False
            elif explicit_rg_pair:
                use_rg_pair_mode = True
            elif gain_pin_1 and gain_pin_2 and is_instrumentation_amp_for_mode:
                use_rg_pair_mode = True
            else:
                use_rg_pair_mode = False

        if use_rg_pair_mode:
            if not gain_pin_1 or not gain_pin_2:
                return False, "gain_mode=rg_pair but gain pin pair not found."

            n1 = self._pin_connected_nets(gain_pin_1)
            n2 = self._pin_connected_nets(gain_pin_2)

            attrs = self.G.nodes[comp_id] if self.G.has_node(comp_id) else {}
            comp_text = " ".join(
                [
                    self._safe_lower(comp_id),
                    self._safe_lower(attrs.get("part_type")),
                    self._safe_lower(attrs.get("part_number")),
                ]
            )

            gain_name_pair = {
                self._safe_lower(self.G.nodes[gain_pin_1].get("name")),
                self._safe_lower(self.G.nodes[gain_pin_2].get("name")),
            }
            has_rg_naming = any("rg" in n for n in gain_name_pair if n)
            is_instrumentation_amp = (
                ("instrument" in comp_text)
                or ("in-amp" in comp_text)
                or bool(re.search(r"\bina\d+", comp_text))
                or has_rg_naming
            )

            requires_resistor = self._parse_bool_param(
                params.get("requires_resistor"),
                default=is_instrumentation_amp or ("requires_resistor" not in params),
            )
            requires_capacitor = self._parse_bool_param(
                params.get("requires_capacitor"),
                default=False,
            )

            allow_open = self._parse_bool_param(params.get("allow_open"), False)

            if not n1 and not n2:
                if allow_open:
                    return True, "Gain-setting pin pair floating, treated as valid open/default-gain mode."
                if not requires_resistor and not requires_capacitor:
                    return True, "Gain-setting pin pair floating, treated as default-gain mode."
                return False, "Gain-setting pin pair is floating."

            if not n1 or not n2:
                return False, "One gain-setting pin connected while the other is floating."

            if set(n1).intersection(set(n2)):
                return False, "Gain-setting pin pair shorted to same net."

            hops = self._propagation_hops(params, "gain_network_hops", 4)
            rg_bridge_kinds = self._parse_kind_set_param(
                params,
                "rg_bridge_kinds",
                {"resistor", "capacitor", "nettie", "testpoint", "jumper", "ferritebead"},
            )

            if requires_resistor:
                has_r_path = self._has_path_with_required_bridge(
                    n1,
                    target_predicate=lambda n: n in set(n2),
                    max_hops=hops,
                    allowed_bridge_kinds=rg_bridge_kinds,
                    required_bridge_kinds={"resistor"},
                    exclude_components={comp_id},
                )
                if not has_r_path:
                    return False, "Missing resistor path between gain-setting pin pair nets."

            if requires_capacitor:
                has_c_path = self._has_path_with_required_bridge(
                    n1,
                    target_predicate=lambda n: n in set(n2),
                    max_hops=hops,
                    allowed_bridge_kinds=rg_bridge_kinds.union({"capacitor"}),
                    required_bridge_kinds={"capacitor"},
                    exclude_components={comp_id},
                )
                if not has_c_path:
                    return False, "Missing capacitor path between gain-setting pin pair nets."

            return True, "Verification passed."

        # ------------------------------------------------------------
        # Mode B: classic op-amp feedback network, backward-compatible.
        # ------------------------------------------------------------
        in_minus = self._resolve_pin_node(comp_id, params.get("in_minus_pin"))
        in_plus = self._resolve_pin_node(comp_id, params.get("in_plus_pin"))
        out_pin = self._resolve_pin_node(comp_id, params.get("out_pin"))

        if not in_minus or not in_plus or not out_pin:
            return False, "Gain-setting pins not found (in_minus/in_plus/out)."

        n_minus = self._pin_connected_nets(in_minus)
        n_plus = self._pin_connected_nets(in_plus)
        n_out = self._pin_connected_nets(out_pin)
        if not n_minus or not n_plus or not n_out:
            return False, "Gain-setting pins have floating net(s)."

        nm = n_minus[0]
        no = n_out[0]

        feedback_kinds = self._parse_kind_set_param(
            params,
            "feedback_element_kinds",
            {"resistor", "digipot", "resistor_ladder"},
        )
        secondary_kinds = self._parse_kind_set_param(
            params,
            "allowed_secondary_branch_kinds",
            {"resistor", "digipot", "dac_output", "resistor_ladder"},
        )

        feedback_elements: Set[str] = set()
        for c in self._components_on_net(nm, exclude={comp_id}):
            if c not in self._components_on_net(no, exclude={comp_id}):
                continue
            if self._normalize_kind_token(self._infer_component_kind(c)) in feedback_kinds:
                feedback_elements.add(c)

        if not feedback_elements:
            return False, (
                "Missing valid feedback element between OUT and IN- nets "
                f"for feedback kinds {sorted(feedback_kinds)}."
            )

        # Also require at least one allowed secondary branch from the IN- side to another reference net.
        div_ok = False
        for comp in self._components_on_net(nm, exclude={comp_id}):
            if comp in feedback_elements:
                continue
            comp_kind = self._normalize_kind_token(self._infer_component_kind(comp))
            if comp_kind in secondary_kinds and any(n != nm for n in self._component_nets(comp)):
                div_ok = True
                break

        # Support direct DAC output participation in gain control, which may not pass through
        # a discrete resistor component.
        if not div_ok and ({"dac_output", "dac"}.intersection(secondary_kinds)):
            for pin in self._net_connected_pins(nm):
                parent = self._pin_parent_component(pin)
                if not parent or parent == comp_id:
                    continue
                pk = self._normalize_kind_token(self._infer_component_kind(parent))
                if pk != "dac":
                    continue
                pin_name = self._safe_lower(self.G.nodes[pin].get("name", ""))
                et = self._safe_lower(self.G.nodes[pin].get("electrical_type", ""))
                if any(tok in pin_name for tok in ["out", "vout", "dac", "ana"]) or et in {"output", "powerout", "analog"}:
                    div_ok = True
                    break

        if not div_ok:
            return False, (
                "IN- net lacks a valid secondary gain-setting branch "
                f"for allowed kinds {sorted(secondary_kinds)}."
            )

        return True, "Verification passed."

    def _check_timing_network(self, comp_id: str, params: dict) -> Tuple[bool, str]:
        """
        REQUIRE_TIMING_NETWORK: RC timing network rule.

        Logic:
        1) All timing_pins must resolve and must not be floating.
        2) The default strict mode uses local pattern recognition to avoid false positives from broad
           domain expansion.
        3) Loose mode keeps the legacy behavior: wide domain propagation plus existence checks in the domain.
        4) Supports explicit required_patterns: cap_to_ground / res_to_ref / rc_pair.
        """
        pins = self._collect_param_pins(params, "timing_pins", "target_pins")
        resolved, missing = self._resolve_pin_list(comp_id, pins)
        if missing:
            return False, f"Timing pin(s) not found: {missing}."

        timing_mode = self._safe_lower(params.get("timing_network_mode", "strict"))
        if timing_mode not in {"strict", "loose"}:
            timing_mode = "strict"

        def _normalize_pattern(token: object) -> str:
            t = self._safe_lower(token).replace("-", "_").replace(" ", "_")
            aliases = {
                "captoground": "cap_to_ground",
                "captognd": "cap_to_ground",
                "restoreference": "res_to_ref",
                "restoref": "res_to_ref",
                "rcpair": "rc_pair",
            }
            compact = t.replace("_", "")
            return aliases.get(compact, t)

        def _parse_pattern_set(raw: object) -> Set[str]:
            if raw is None:
                return set()
            values: List[str]
            if isinstance(raw, list):
                values = [str(x) for x in raw]
            elif isinstance(raw, str):
                values = re.split(r"[,;|]", raw)
            else:
                return set()
            out = {_normalize_pattern(v) for v in values if str(v).strip()}
            return {v for v in out if v in {"cap_to_ground", "res_to_ref", "rc_pair"}}

        explicit_patterns = _parse_pattern_set(params.get("required_patterns"))
        reference_net_type = params.get("timing_reference_net_type", params.get("reference_net_type", "power"))

        if timing_mode == "loose":
            timing_nets: Set[str] = set()
            for p in resolved:
                nets = self._pin_connected_nets(p)
                if not nets:
                    return False, f"Timing pin '{p}' is floating."
                timing_nets.update(nets)

            soft_start_mode = False
            for p in resolved:
                pin_name = self._safe_lower(self.G.nodes[p].get("name", ""))
                if pin_name in {"ss", "softstart", "soft_start", "soft-start"} or ("soft" in pin_name and "start" in pin_name):
                    soft_start_mode = True
                    break

            requires_resistor = self._parse_bool_param(
                params.get("requires_resistor"),
                default=not soft_start_mode,
            )
            requires_capacitor = self._parse_bool_param(
                params.get("requires_capacitor"),
                default=True,
            )

            hops = self._propagation_hops(params, "timing_network_hops", 3)
            bridge_kinds = self._resolve_propagation_bridge_kinds(
                params,
                {"resistor", "capacitor", "inductor", "ferritebead", "passive"},
            )
            timing_domain = self._propagate_nets(
                timing_nets,
                max_hops=hops,
                bridge_kinds=bridge_kinds,
                exclude_components={comp_id},
                terminal_net_types={"ground", "power"},
            )

            domain_comps: Set[str] = set()
            for n in timing_domain:
                domain_comps.update(self._components_on_net(n, exclude={comp_id}))

            has_r = any(self._component_matches_kind(c, "resistor") for c in domain_comps)
            has_c = any(self._component_matches_kind(c, "capacitor") for c in domain_comps)

            if requires_resistor and not has_r:
                return False, "Timing network requires resistor(s) in reachable timing topology (loose mode)."
            if requires_capacitor and not has_c:
                return False, "Timing network requires capacitor(s) in reachable timing topology (loose mode)."
            return True, "Verification passed."

        max_local_hops = self._propagation_hops(params, "max_local_hops", 2)
        local_bridge_kinds = self._parse_kind_set_param(
            params,
            "local_bridge_kinds",
            {"resistor", "capacitor", "nettie", "testpoint", "jumper", "passive"},
        )

        def _pin_default_patterns(pin_name: str) -> Set[str]:
            pn = self._safe_lower(pin_name)
            if pn in {"ss", "softstart", "soft_start", "soft-start"} or ("soft" in pn and "start" in pn):
                return {"cap_to_ground"}
            if pn == "ct" or pn.startswith("ct"):
                return {"cap_to_ground"}
            if pn == "rt" or pn.startswith("rt"):
                return {"res_to_ref"}
            if any(tok in pn for tok in ["comp", "osc", "tim", "clk"]):
                return {"rc_pair"}
            # Unknown timing pins fall back to rc_pair to avoid treating arbitrary nearby components
            # as a valid timing network.
            return {"rc_pair"}

        def _has_cap_to_ground(seed_nets: Set[str], local_domain: Set[str]) -> bool:
            for n in seed_nets.union(local_domain):
                if self._net_has_component_to_ref_net(n, "capacitor", "ground"):
                    return True
            return False

        def _has_res_to_reference(seed_nets: Set[str], local_domain: Set[str]) -> bool:
            for n in seed_nets.union(local_domain):
                for r in self._resistors_on_net(n):
                    for other in self._component_nets(r):
                        if other == n:
                            continue
                        if self._net_matches_reference(other, str(reference_net_type)):
                            return True
            return False

        def _has_rc_pair(seed_nets: Set[str], local_domain: Set[str]) -> bool:
            # rc_pair uses "coexistence in the local domain" semantics and does not require R/C to be
            # on the exact same net.
            return _has_cap_to_ground(seed_nets, local_domain) and _has_res_to_reference(seed_nets, local_domain)

        for p in resolved:
            nets = set(self._pin_connected_nets(p))
            if not nets:
                return False, f"Timing pin '{p}' is floating."

            local_domain = self._propagate_nets(
                nets,
                max_hops=max_local_hops,
                bridge_kinds=local_bridge_kinds,
                exclude_components={comp_id},
            )

            patterns = set(explicit_patterns) if explicit_patterns else _pin_default_patterns(self.G.nodes[p].get("name", ""))

            # Backward compatibility for explicit requires_resistor/requires_capacitor.
            if not explicit_patterns and ("requires_resistor" in params or "requires_capacitor" in params):
                req_r = self._parse_bool_param(params.get("requires_resistor"), False)
                req_c = self._parse_bool_param(params.get("requires_capacitor"), True)
                if req_r and req_c:
                    patterns = {"rc_pair"}
                elif req_r:
                    patterns = {"res_to_ref"}
                elif req_c:
                    patterns = {"cap_to_ground"}
                else:
                    patterns = set()

            for pattern in patterns:
                if pattern == "cap_to_ground" and not _has_cap_to_ground(nets, local_domain):
                    return False, f"Timing pin '{p}' requires cap_to_ground pattern."
                if pattern == "res_to_ref" and not _has_res_to_reference(nets, local_domain):
                    return False, f"Timing pin '{p}' requires res_to_ref pattern."
                if pattern == "rc_pair" and not _has_rc_pair(nets, local_domain):
                    return False, f"Timing pin '{p}' requires rc_pair pattern."

        return True, "Verification passed."
